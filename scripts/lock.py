"""Write requirements.lock: every library the pipeline needs on Linux (the Docker image, CI),
pinned to the exact version installed and tested in this environment, so an image built
months from now gets the same libraries. Run after upgrading anything:

    python scripts/lock.py

torch and torchvision are left out: the Dockerfile installs their CPU-only builds from
PyTorch's own index, pinned there.
"""
import importlib.metadata as md
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

LINUX_312 = {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix",
             "platform_machine": "x86_64", "python_version": "3.12",
             "python_full_version": "3.12.15", "implementation_name": "cpython",
             "platform_python_implementation": "CPython"}
LEFT_OUT = {"torch", "torchvision", "ingest"}


def _project_requirements(extras: set[str]) -> list[str]:
    """The pipeline's own requirements, read from pyproject.toml (not from install metadata,
    which is only as new as the last `pip install -e .`)."""
    import tomllib
    project = tomllib.loads((Path(__file__).resolve().parent.parent / "pyproject.toml")
                            .read_text(encoding="utf-8"))["project"]
    reqs = list(project["dependencies"])
    for extra in extras:
        reqs += project.get("optional-dependencies", {}).get(extra, [])
    return reqs


def closure(root: str, extras: set[str]) -> tuple[dict[str, str], set[str]]:
    """Pinned versions of everything `root[extras]` needs on Linux, and any requirement
    that isn't installed here (a Linux-only dependency) to list unpinned."""
    pinned, missing, done = {}, set(), set()
    todo = [(root, frozenset(extras))]
    while todo:
        name, wanted = todo.pop()
        if (canonicalize_name(name), wanted) in done:
            continue
        done.add((canonicalize_name(name), wanted))
        requires = (_project_requirements(set(wanted)) if name == root
                    else md.distribution(name).requires or [])
        for raw in requires:
            req = Requirement(raw)
            if req.marker and not any(req.marker.evaluate({**LINUX_312, "extra": e})
                                      for e in (wanted or {""})):
                continue
            key = canonicalize_name(req.name)
            if key in LEFT_OUT:
                continue
            try:
                pinned[key] = md.distribution(req.name).version
            except md.PackageNotFoundError:
                missing.add(str(req))
                continue
            todo.append((req.name, frozenset(req.extras)))
    return pinned, missing


if __name__ == "__main__":
    pinned, missing = closure("ingest", {"server", "gpu"})
    lines = ["# Generated by scripts/lock.py: exact versions of everything the pipeline needs",
             "# on Linux (Python 3.12). torch/torchvision: CPU builds, pinned in the Dockerfile."]
    lines += [f"{name}=={version}" for name, version in sorted(pinned.items())]
    lines += [f"{req}  # not installed where the lock was made" for req in sorted(missing)]
    out = Path(__file__).resolve().parent.parent / "requirements.lock"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}: {len(pinned)} pinned, {len(missing)} unpinned")
